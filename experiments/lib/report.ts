import { mkdirSync, writeFileSync, appendFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = join(here, "..", "..");
export const RESULTS_DIR = join(REPO_ROOT, "packages", "core", "verified", "experiments");
export const LOGS_DIR = join(here, "..", "logs");

export type Outcome = "RAN" | "BLOCKED" | "FAILED";

export class Report {
  private readonly lines: string[] = [];
  private readonly started = new Date();
  readonly date: string;

  constructor(
    readonly name: string,
    readonly question: string,
  ) {
    this.date = this.started.toISOString().slice(0, 10);
    mkdirSync(RESULTS_DIR, { recursive: true });
    mkdirSync(LOGS_DIR, { recursive: true });
  }

  section(title: string): void {
    this.lines.push("", `## ${title}`, "");
  }

  line(text = ""): void {
    this.lines.push(text);
    appendFileSync(
      join(LOGS_DIR, `${this.date}-${this.name}.log`),
      `${new Date().toISOString()} ${text}\n`,
    );
    console.error(text);
  }

  code(label: string, body: string, lang = ""): void {
    this.lines.push("", `${label}:`, "", `\`\`\`${lang}`, body.trimEnd(), "```", "");
  }

  finish(outcome: Outcome, verdict: string): string {
    const header = [
      `# Experiment: ${this.name}`,
      "",
      `- Date: ${this.started.toISOString()}`,
      `- Outcome: **${outcome}**`,
      `- Question: ${this.question}`,
      `- Verdict: ${verdict}`,
      "",
      "Generated by `experiments/" +
        this.name +
        ".ts`. Read this file; do not re-run it to find out what happened.",
    ];
    const file = join(RESULTS_DIR, `${this.date}-${this.name}.md`);
    writeFileSync(file, `${[...header, ...this.lines].join("\n")}\n`);
    console.error(`\nreport written: ${file}`);
    return file;
  }
}

export function env(name: string): string | undefined {
  const value = process.env[name];
  return value === undefined || value === "" ? undefined : value;
}

export async function fetchJson(url: string): Promise<unknown> {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${url} -> HTTP ${String(response.status)}`);
  }
  return response.json();
}
